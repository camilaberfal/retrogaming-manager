    public void cargarTabla() {

    DefaultTableModel modelo =
            (DefaultTableModel) tblJuguetes.getModel();

    modelo.setRowCount(0);

    for (int i = 0; i < gestion.getContador(); i++) {

        Juguete j = gestion.getJuguete(i);

        Object[] fila = {
            j.getCodigo(),
            j.getNombre(),
            j.getCategoria(),
            j.getAnioFabricacion(),
            j.getPrecioBase(),
            j.calcularPrecioVenta(),
            j.getStock(),
            j.getEstado()
        };

        modelo.addRow(fila);
    }
    }
    
