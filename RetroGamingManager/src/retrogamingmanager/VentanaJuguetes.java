    private Juguete obtenerDatos() {

        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        
        String categoria = cboCategoria.getSelectedItem().toString();
        String estado = cboEstado.getSelectedItem().toString();
        
        if (categoria.equals("Seleccione...")) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar una categoría.");
            return null;
        }

        if (estado.equals("Seleccione...")) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un estado.");
            return null;
        }
        
        int anio = Integer.parseInt(txtAnio.getText().trim());
        double precio = Double.parseDouble(txtPrecio.getText().trim());
        int stock = Integer.parseInt(txtStock.getText().trim());

        
        
        Juguete j;

        if (categoria.equals("Figura de Acción")) {
            j = new FiguraAccion(codigo, nombre, anio,
                    precio, stock, estado);
        } else if (categoria.equals("Consola Retro")) {
            j = new ConsolaRetro(codigo, nombre, anio,
                    precio, stock, estado);
        } else {
            j = new JuegoMesa(codigo, nombre, anio,
                    precio, stock, estado);
        }

        return j;
    }
    
    
