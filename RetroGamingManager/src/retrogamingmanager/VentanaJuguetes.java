    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigo.getText().trim();

        Juguete j = gestion.buscar(codigo);

        if (j != null) {
            txtNombre.setText(j.getNombre());
            txtAnio.setText(String.valueOf(j.getAnioFabricacion()));
            txtPrecio.setText(String.valueOf(j.getPrecioBase()));
            txtStock.setText(String.valueOf(j.getStock()));

            cboCategoria.setSelectedItem(j.getCategoria());
            cboEstado.setSelectedItem(j.getEstado());

            JOptionPane.showMessageDialog(this, "Juguete encontrado correctamente.");

        } 
        else {
            JOptionPane.showMessageDialog(this, "No se encontró el juguete.");
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        String codigo = txtCodigo.getText().trim();

        if (gestion.buscar(codigo) == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el juguete.");
            return;
        }

        try {
            Juguete nuevo = obtenerDatos();
            
            if (nuevo == null) {
                return;
            }

            gestion.modificar(codigo, nuevo);

            JOptionPane.showMessageDialog(this, gestion.getMensaje());

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingrese números válidos en año, precio y stock.");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();

        Juguete j = gestion.buscar(codigo);

        if (j == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el juguete.");
            return;
        }

        String[] opciones = {"Sí", "No"};

        int opcion = JOptionPane.showOptionDialog(this,
                "¿Desea eliminar el juguete " + j.getNombre() + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[1]);

        if (opcion == 0) {

            gestion.eliminar(codigo);

            JOptionPane.showMessageDialog(this,
                    gestion.getMensaje());
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

