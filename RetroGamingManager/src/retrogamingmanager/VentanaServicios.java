    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            ServicioAdicional s = obtenerDatos();

            gestion.registrar(s);

            JOptionPane.showMessageDialog(this,
                    gestion.getMensaje());

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingrese números válidos en precio y stock.");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigo.getText().trim();

        ServicioAdicional s = gestion.buscar(codigo);

        if (s != null) {
            txtNombre.setText(s.getNombre());
            txtPrecio.setText(String.valueOf(s.getPrecioUnitario()));
            txtStock.setText(String.valueOf(s.getStock()));

            JOptionPane.showMessageDialog(this,
                    "Servicio encontrado correctamente.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el servicio.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        String codigo = txtCodigo.getText().trim();

        if (gestion.buscar(codigo) == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el servicio.");
            return;
        }

        try {
            ServicioAdicional nuevo = obtenerDatos();

            gestion.modificar(codigo, nuevo);

            JOptionPane.showMessageDialog(this,
                    gestion.getMensaje());

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese números válidos en precio y stock.");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();

        ServicioAdicional s = gestion.buscar(codigo);

        if (s == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el servicio.");
            return;
        }

        String[] opciones = {"Sí", "No"};

        int opcion = JOptionPane.showOptionDialog(this,
                "¿Desea eliminar el servicio " + s.getNombre() + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[1]);

        if (opcion == 0) {
            gestion.eliminar(codigo);

            JOptionPane.showMessageDialog(this,
                    gestion.getMensaje());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

