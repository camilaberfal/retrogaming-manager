    private void ingresar() {
        String usuario = usuarioField.getText().trim();
        String clave = new String(pwdClave.getPassword());

        if (usuario.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese usuario y contraseña.", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Empleados empleado = gestionPersonal.validarLogin(usuario, clave);
        if (empleado == null) {
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.", "Error de acceso", JOptionPane.ERROR_MESSAGE);
            pwdClave.setText("");
            pwdClave.requestFocus();
            return;
        }

        new MenuPrincipal(empleado, gestionPersonal, gestionClientes).setVisible(true);
        dispose();
    }
