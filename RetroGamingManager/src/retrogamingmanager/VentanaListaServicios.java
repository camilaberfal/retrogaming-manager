    public void cargarTabla() {

        DefaultTableModel modelo =
                (DefaultTableModel) tblServicios.getModel();

        modelo.setRowCount(0);

        for (int i = 0; i < gestion.getContador(); i++) {

            ServicioAdicional s = gestion.getServicio(i);

            Object[] fila = {
                s.getCodigo(),
                s.getNombre(),
                s.getPrecioUnitario(),
                s.getStock()
            };

            modelo.addRow(fila);
        }
    }
    
